/**
 * Turns the written vocabulary into the pairs a filter group needs: the label it is shown under and
 * the name the site is asked for.
 */
internal fun tagOptions(data: String): List<Pair<String, String>> = data.trimIndent().lines().map(String::trim).filter(String::isNotEmpty).map { line ->
    val (label, name) = line.split('|', limit = 2)
    label to name
}
